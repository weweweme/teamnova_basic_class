-- 006_drafts.sql
--   글쓰기 임시저장(초안)을 세션이 아니라 표에 담는다.
--
--   [처음엔 세션에 담았다 — 왜 옮기나]
--     세션은 **창을 닫으면 사라진다.** 그게 세션의 성질이라 고칠 수가 없다.
--     그런데 임시저장은 "브라우저가 꺼져도 살아 있어야" 쓸모가 있는 기능이다.
--     기능의 성격과 그릇의 성질이 어긋나 있었다.
--
--   [세션에 두었을 때 감수해야 했던 것들]
--     · 창을 닫으면 소멸 · 30분이면 만료 · 다른 기기에서 못 이어 씀
--     · 세션은 **요청마다 통째로 읽고 쓴다** → 본문(최대 5,000자)을 넣으면
--       글과 아무 상관없는 페이지까지 무거워진다. 그래서 초안을 1개로 제한해야 했다.
--     표로 옮기면 이 제약이 전부 없어진다 — 필요할 때만 읽으니 개수도 넉넉히 둘 수 있다.
--
--   [★ 그릇을 고르는 질문]
--     "이 값의 주인이 누구인가"를 먼저 묻는다.
--       · 최근 본 글  → 주인이 **브라우저** (로그인 안 해도 쌓인다)  → 쿠키
--       · 로그인 신원 → 주인이 **이 방문**                         → 세션
--       · 글 초안     → 주인이 **회원**   (기기가 바뀌어도 내 것)   → DB
--     초안은 글쓰기 자체가 로그인 필수라 주인이 언제나 회원이다. 그래서 표가 맞다.
--
--   [왜 posts 표에 'draft' 상태로 안 넣나]
--     초안은 아직 글이 아니다. posts에 넣으면 목록·검색·랭킹·알림이 전부
--     "이건 초안인가?"를 매번 걸러야 한다. 완성된 글만 posts에 있는 편이 훨씬 단순하다.
-- ============================================================

CREATE TABLE IF NOT EXISTS drafts (
    user_id    INT          NOT NULL,        -- 누구의 초안인가 → users.id
    work_slug  VARCHAR(100) NOT NULL,        -- 어느 작품 게시판에 쓰던 글인가 (tmdb-496243)

    title      VARCHAR(200) NOT NULL DEFAULT '',
    content    TEXT         NOT NULL,
    sentiment  VARCHAR(10)  NOT NULL DEFAULT '',

    updated_at DATETIME     NOT NULL,        -- 마지막으로 저장된 시각 (오래된 것 정리 기준)

    -- ★ 복합 기본키 = "한 사람이 한 작품에 초안 하나".
    --   likes·votes가 (user_id, post_id)로 '1인 1회'를 보장하는 것과 같은 방식이다.
    --   같은 작품에 또 저장하면 새 줄이 생기는 게 아니라 그 줄을 덮어쓴다.
    PRIMARY KEY (user_id, work_slug),

    -- 오래된 초안을 정리할 때 이 칼럼으로 훑으므로 색인을 둔다.
    INDEX idx_drafts_updated (updated_at),

    -- 회원이 사라지면 초안도 함께. (작성물이 아니라 '쓰다 만 메모'이므로 남길 이유가 없다)
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
