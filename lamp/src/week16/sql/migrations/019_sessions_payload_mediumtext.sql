-- 019: sessions.payload 를 TEXT → MEDIUMTEXT 로 넓힌다
--
--   [왜]
--     조회 판정 서랍(`seen`)에 **개수 상한을 두지 않기로** 했다.
--     상한이 있으면 밀려난 글이 오늘 다시 세어져서, 부풀리기를 막으려는 장치에
--     "N번째부터는 안 막힘"이라는 구멍이 생긴다. 판정은 정확해야 한다.
--
--   ★ 그러면 담기는 양이 자라는데, 그건 **저장소가 감당할 문제**다.
--     TEXT는 65,535바이트라 1칸(약 9바이트) 기준 6,500개쯤에서 막힌다.
--     MEDIUMTEXT는 16MB — 같은 기준으로 약 180만 개다. 사실상 천장이 없다.
--
--   ⚠️ payload가 칼럼을 넘으면 **저장이 통째로 실패**하고, 그러면 그 요청의
--     세션이 사라진다(로그인이 안 되는 것처럼 보인다). 넉넉히 잡아 두는 편이 안전하다.
--
--   ※ 넓혀도 평소 비용은 그대로다 — 실제 저장 크기는 담긴 만큼이고,
--     MEDIUMTEXT는 길이를 적는 머리말이 2바이트에서 3바이트로 늘 뿐이다.

ALTER TABLE sessions MODIFY payload MEDIUMTEXT NOT NULL;
