-- 014_device_keys.sql
--   기기마다 **꺼낼 수 없는 도장**을 하나씩 갖게 하고, 그 도장의 '공개된 짝'만 서버에 둔다.
--   (업계 용어로는 공개키 · 서명. 이 파일에서는 도장/자국으로 부른다)
--
--   [★ 왜 필요한가 — 쿠키만으로는 못 푸는 문제가 있다]
--     지금까지 우리 인증은 **번호표를 내밀면 통과**하는 방식이었다(bearer).
--     그래서 번호표를 훔치면 **비밀번호도 2단계 인증도 없이** 그 사람이 된다.
--     짧게(회전) · 얕게(재인증) · 보이게(기기 목록)로 **줄이기는** 했지만,
--     **없앨 수는 없었다.** 내미는 것만으로 통과하는 값이라는 성질 자체가 원인이기 때문이다.
--
--     ★ DBSC 설명서(W3C)가 같은 말을 한다 —
--       "cookies ... only lend themselves to bearer-token schemes"
--
--   [★★ 그래서 무엇을 바꾸나 — '내미는 것' 대신 '찍어 보이는 것']
--     브라우저 안에 **꺼낼 수 없는 도장**을 하나 만든다(WebCrypto, extractable=false).
--     서버는 매번 아무 숫자나 던지고, 브라우저는 **도장으로 찍은 자국만** 보낸다.
--       · 도장은 브라우저 밖으로 안 나온다   → **훔쳐갈 것 자체가 없다**
--       · 숫자가 매번 바뀌니 자국도 매번 다르다 → **베껴놔도 다음번엔 안 통한다**
--
--   [★ 그런데도 쿠키를 없애지 않는다 — 도장이 느리기 때문]
--     DBSC 설명서에 실측이 있다: 도장 한 번에 **P50 200ms · P95 600ms**.
--     매 요청 찍으면 클릭할 때마다 그만큼 멈춘다. 그래서 DBSC도 이렇게 한다:
--       평소 요청     → 짧은 쿠키로 통과      (빠르다)
--       쿠키 만료 때  → 도장 찍고 새 쿠키     (느려도 가끔이라 괜찮다)
--     ★ 우리도 똑같이 한다. **바뀐 것은 '연장 조건' 하나뿐이다** —
--       전에는 요청만 오면 연장됐고, 이제는 **도장을 찍어야** 연장된다.
--
--   [★ 왜 새 표를 안 만들고 user_devices에 붙이나]
--     우리 기준은 "수명과 주인이 같으면 합치고, 다르면 나눈다"였다.
--       · 도장의 주인 = **그 기기**       (user_devices와 같다)
--       · 도장의 수명 = **기기 기록과 동일** (기기를 끊으면 도장도 함께 죽어야 한다)
--     → 같은 줄에 둔다. 실제로 기기 끊기(revoke_device) 한 번으로 도장까지 사라진다.
--
--   [★ 담는 것은 '공개된 짝'뿐이다]
--     도장 본체(개인키)는 **브라우저 밖으로 나올 수 없으므로 서버에 올 방법이 아예 없다.**
--     서버가 받는 것은 자국을 대조하는 데만 쓰이는 공개키이고,
--     이건 **새어나가도 아무 피해가 없다** — 그걸로는 자국을 만들 수 없기 때문이다.
--     ※ 비밀번호 해시와 같은 성질이다. "대조는 되는데 위조는 안 되는 값."
-- ============================================================

-- 브라우저가 export('spki')로 뽑아준 공개키를 그대로 담는다 (base64, P-256이면 124글자).
--   ★ 원본 형식(DER/SPKI)을 유지한다 — 서버가 형식을 손으로 조립하면 그 코드가 곧 버그 자리가 된다.
ALTER TABLE user_devices ADD COLUMN public_key VARCHAR(255) NULL AFTER user_agent;

-- 도장을 언제 등록했나. (설정 화면에서 "이 기기는 도장 있음"을 보여줄 때 쓴다)
ALTER TABLE user_devices ADD COLUMN key_added_at DATETIME NULL AFTER public_key;

-- ★ 도장을 마지막으로 확인한 시각. 세션이 아니라 **기기 줄**에 적는다.
--   [왜 세션이 아닌가]
--     세션에만 적으면 **세션을 훔친 쪽도 그 값을 같이 가져간다.** 그러면 확인한 적 없는데
--     확인한 것처럼 보인다. 판정 근거는 훔친 사람이 들고 갈 수 없는 곳에 있어야 한다.
--   ※ 다만 최종 판정은 (세션 + 이 줄) 둘 다 본다 — session.php의 key_proof_at 주석 참고.
ALTER TABLE user_devices ADD COLUMN key_proved_at DATETIME NULL AFTER key_added_at;
