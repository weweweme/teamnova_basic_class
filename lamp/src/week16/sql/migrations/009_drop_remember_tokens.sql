-- 009_drop_remember_tokens.sql
--   '로그인 유지'(자동 로그인) 기능을 **없앤다.**
--
--   [만들었다가 없앤 이유 — 이번 주차에서 가장 오래 고민한 지점]
--     자동 로그인은 결국 **"오래 사는 열쇠를 사용자 PC에 맡기는 것"** 이다.
--     맡기는 순간 그 열쇠를 훔칠 수 있고, 훔치면 30일간 그 사람이 된다.
--     비밀번호도 2FA도 필요 없다 — 그 단계를 뚫는 게 아니라 **건너뛴다.**
--
--   [막아보려고 한 것들 — 그리고 왜 부족했나]
--     ① httponly · samesite · secure    → 훔칠 기회는 줄지만 없어지지는 않는다
--     ② 토큰 회전(쓸 때마다 새것)        → 훔친 표의 수명은 줄지만 여전히 유효하다
--     ③ 재사용 탐지(series 계열)         → **탐지는 주인이 그 자리로 돌아와야 작동한다.**
--        주인이 그 브라우저를 한동안 안 켜면 며칠이 지나도 안 걸린다.
--        주인이 비밀번호로 새로 로그인해도 **도난당한 계열은 그대로 살아 있다.**
--     → 즉 **완화는 되지만 해결은 안 된다.** 이것은 우리 구현의 결함이 아니라
--       '소지자에게 권리를 주는(bearer)' 모델의 성질이다.
--
--   [★ 그래서 그릇을 바꾸는 대신 '맡기지 않기'를 골랐다]
--     로그인 상태는 이제 **세션 하나로만** 유지한다.
--     세션 쿠키(PHPSESSID)는 **만료 시각이 없어서 브라우저를 닫으면 사라진다.**
--     훔칠 수 있는 것이 '30분짜리 세션 번호표' 하나로 줄어든다.
--     ※ 은행이 자동 로그인을 제공하지 않는 이유가 정확히 이것이다.
--
--   [무엇을 잃었나 — 정직하게]
--     올 때마다 로그인해야 한다. **편의를 내주고 위험을 줄인 거래**이고,
--     서비스 성격에 따라 반대로 고르는 것도 맞는 선택이다.
--     (리뷰 커뮤니티에 30일 자동 로그인이 꼭 필요한가? 라는 질문에 우리는 '아니오'라고 답했다)
--
--   [★ 진짜 해법은 다른 층에 있다]
--     "훔쳐도 소용없게" 만들려면 **쿠키를 기기 개인키에 묶어야** 한다(DBSC).
--     쿠키·세션만으로는 도달할 수 없는 지점이라, 이번에는 범위 밖으로 두었다.
-- ============================================================

DROP TABLE IF EXISTS remember_tokens;
