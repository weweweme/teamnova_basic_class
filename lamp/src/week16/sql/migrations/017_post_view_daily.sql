-- ============================================================
-- 017_post_view_daily.sql
--   조회 기록을 **판정용과 집계용으로 나눈다.**
--
--   [★ 무엇이 문제였나 — 피드백에서 나온 지적]
--     *"조회수 뻥튀기를 막는 기술에서, 블랙리스트를 만드는 기술로 넘어갔다."*
--
--     판정에 필요한 것은 **"오늘 이 사람이 이 글을 봤나"** 하나뿐이다.
--     그런데 `post_views` 를 7일 보관하면서 **7일치 열람 이력**을 들고 있었다.
--     ★★ 게다가 우리 스스로와 모순이었다 — 쿠키 동의에서 *"최근 본 글은 물어봐야 한다"* 고
--       해놓고, 서버에는 동의 없이 같은 성격의 기록을 쌓고 있었다.
--
--   [왜 7일이었나 — 한 표가 두 일을 하고 있었다]
--     판정  "오늘 봤나"        하루면 충분하다
--     집계  "최근 며칠간 몇 번" '지금 뜨는 글'이 7일을 센다   ← 이쪽이 기간을 끌어올렸다
--     => 집계 때문에 **판정 기록까지 7일** 살아 있었다
--
--   [★ 그래서 나눈다 — 집계에는 '누가'가 필요 없다]
--     post_views       (글, 사람, 날짜)   **1일**  판정에만 쓴다
--     post_view_daily  (글, 날짜, 횟수)   **7일**  숫자만. 누가 봤는지가 없다
--
--     ★ 열람 이력은 하루면 사라지고, 오래 남는 쪽에는 **사람이 안 들어 있다.**
--       "필요한 만큼만, 필요한 기간만" 이 두 표로 갈린다.
--
--   ※ 조회수를 세는 순간에만 이 표가 늘어난다(사람당 하루 한 번꼴)
--     → 원래 `posts.views` 를 갱신하던 그 자리에 한 줄이 더 붙을 뿐이다.
-- ============================================================

CREATE TABLE IF NOT EXISTS post_view_daily (
    post_id   INT  NOT NULL,
    viewed_on DATE NOT NULL,

    -- 그날 이 글이 몇 번 세어졌나. **누가 봤는지는 담지 않는다.**
    views     INT  NOT NULL DEFAULT 0,

    PRIMARY KEY (post_id, viewed_on),
    -- '지금 뜨는 글'은 "최근 N일" 로 훑는다 → 날짜가 앞에 오는 색인이 필요하다.
    INDEX idx_view_daily_day (viewed_on, post_id),

    FOREIGN KEY (post_id) REFERENCES posts(id) ON DELETE CASCADE
);
