-- 018_drop_post_views.sql
--   조회 **판정 기록**을 서버 표에서 걷어낸다. 판정은 세션으로 돌아간다.
--
--   [★ 왜 되돌리나 — 피드백]
--     *"조회수 뻥튀기를 막는 기술에서, 블랙리스트를 만드는 기술로 넘어갔다."*
--     판정에 필요한 건 **"오늘 이 사람이 이 글을 봤나"** 하나뿐인데,
--     그걸 알자고 **누가 무엇을 봤는지**를 서버에 남기고 있었다.
--     ★ 쿠키 동의에서 *"최근 본 글은 물어봐야 한다"* 고 해놓고,
--       서버에는 동의 없이 같은 성격의 기록을 쌓던 셈이라 앞뒤가 안 맞았다.
--
--   [무엇이 남고 무엇이 사라지나]
--     사라짐  post_views       (글, 사람, 날짜)  → 세션으로
--     남음    post_view_daily  (글, 날짜, 횟수)  → '지금 뜨는 글'용. **누가**가 없다
--
--   [★ 세션으로 돌아가되 예전 실패는 반복하지 않는다]
--     처음 세션 방식의 문제는 **글 번호만 담아 시각이 없었다**는 것이었다.
--     → 이제 [글번호 => 본 날짜] 로 담고, 개수 상한(50)도 둔다.
--
--   [내준 것]
--     브라우저를 닫으면 판정 기록도 사라져 **그만큼은 다시 세어진다.**
--     표로 하면 막히지만, 그건 **열람 이력을 서버에 쌓는 대가**로 얻는 것이었다.
--     ★ 조회수 정확도와 열람 기록을 저울에 올려 **정확도를 내주기로 했다.**
--
--   ※ 012·013·015·017 로 이어진 판단이 여기서 한 번 더 뒤집힌다.
--     마이그레이션은 **되돌린 판단도 이력으로 남긴다.**
-- ============================================================

DROP TABLE IF EXISTS post_views;
