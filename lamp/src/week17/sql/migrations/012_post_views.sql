-- ============================================================
-- 012_post_views.sql
--   조회수 중복 방지를 **세션에서 표로** 옮긴다. (Discourse와 같은 구조)
--
--   [★ 무엇이 문제였나 — "시간을 아무도 정하지 않았다"]
--     지금까지는 세션에 본 글 번호를 쌓아두고 "이미 있으면 안 센다"가 전부였다:
--       $_SESSION['viewed_posts'] = [12, 9, 3]
--     여기엔 **시각이 없다.** 그래서 "몇 시간 뒤에 다시 셀 것인가"를 정할 수가 없었다.
--     대신 **세션 수명(유휴 20분 / TTL 30분)이 그 정책을 우연히 대신 정하고 있었다.**
--     ★ 결정한 적 없는 값이 정책이 되어 있었던 것이다.
--
--     게다가 세션 쿠키는 **브라우저를 닫으면 사라진다** → 창을 껐다 켜면 조회수가 다시 올랐다.
--     F5 연타는 막았지만 정작 부풀리기는 아주 쉬웠다.
--     그리고 배열에 **상한이 없어서** 글을 많이 볼수록 세션 payload가 계속 무거워졌다
--     (세션은 요청마다 통째로 읽고 쓴다 — 글과 무관한 페이지까지 느려진다).
--
--   [★★ 실무는 어떻게 하나 — 찾아본 것]
--     · **Discourse**       : topic_views 표. `viewed_at`이 DATE. **하루 1회**.
--                             로그인 사용자는 user_id, 아니면 IP. Redis를 문지기로 앞에 둔다.
--     · **django-hitcount** : HITCOUNT_KEEP_HIT_ACTIVE 기본 **7일**. 세션키+IP+UA로 판정.
--     공통점은 셋이다: ①**창이 코드에 숫자로 적혀 있다** ②세션이 아니라 **별도 표**에 둔다
--     ③판정 키를 **여러 단계**로 둔다.  → 우리에게 없던 것이 정확히 이 셋이었다.
--
--   [우리 설계 — Discourse 구조에 한 단을 더]
--     판정 키를 셋으로 나눈다:
--       로그인      → 'u:<회원번호>'    가장 정확
--       device 쿠키 → 'd:<기기번호>'    ★ Discourse에 없는 단계.
--                                       IP는 공유되지만(회사망·공용 와이파이) 쿠키는 브라우저마다 하나다
--       둘 다 없음  → 'i:<IP 지문>'     쿠키를 안 받는 상대(스크립트)가 여기로 떨어진다
--
--   [왜 DATE인가 — 시각이 아니라 날짜]
--     Discourse가 DATE를 쓰는 이유가 있다. "하루에 한 번"은 사람이 이해하기 쉽고,
--     **시각 계산이 통째로 사라진다** — DB는 UTC, PHP는 KST라 시각을 넘기면 어긋난다
--     (login_attempts에서 실제로 9시간 밀려 잠금이 안 걸린 적이 있다).
--
--   [비용 — 오히려 내려간다]
--     지금은 조회할 때마다 `UPDATE posts SET views = views + 1` 을 친다.
--     인기 글이면 **한 행에 쓰기가 몰려** 잠금 경합이 생기는 자리다.
--     이 표가 생기면 그 UPDATE가 **사람당 하루 한 번**으로 줄어든다.
--     늘어나는 건 '처음 보는 조회' 하나당 INSERT 한 번인데, 복합 기본키라 인덱스 한 번이면 끝난다.
-- ============================================================

CREATE TABLE IF NOT EXISTS post_views (
    post_id    INT         NOT NULL,          -- 어느 글 → posts.id

    -- 누가 봤나. 'u:1' · 'd:4f8a…' · 'i:<sha256>' 중 하나.
    --   ★ 접두어를 붙이는 이유: 표만 봐도 **무엇으로 판정했는지** 알 수 있다.
    --     번호만 담으면 회원 1번과 어떤 기기가 우연히 같아 보일 여지도 생긴다.
    viewer_key VARCHAR(72) NOT NULL,

    -- ★ 시각이 아니라 **날짜**. "같은 날이면 안 센다".
    viewed_on  DATE        NOT NULL,

    -- ★★ 복합 기본키 = "한 사람이 한 글에 한 줄".
    --   likes·votes가 (user_id, post_id)로 '1인 1회'를 보장하는 것과 같은 방식이다.
    --   덕분에 행이 무한정 늘어나지 않는다 — 다시 보면 새 줄이 아니라 날짜만 바뀐다.
    PRIMARY KEY (post_id, viewer_key),

    -- 지난 날짜를 훑어 지울 때 쓴다.
    INDEX idx_post_views_day (viewed_on),

    -- 글이 사라지면 조회 기록도 함께. (집계용 기록이라 남길 이유가 없다)
    FOREIGN KEY (post_id) REFERENCES posts(id) ON DELETE CASCADE
);
