<?php
// ============================================================
// view_id.php — 조회수 중복 판정에만 쓰는 브라우저 번호
//
//   [★ 왜 device 쿠키에서 떼어냈나 — 한 쿠키가 두 일을 하고 있었다]
//     `device` 하나로 **기기 목록(보안)** 과 **조회수 중복 방지(측정)** 를 함께 했다.
//     편해 보였지만 규정이 그걸 막는다:
//
//       📄 Article 29 WP, Opinion 04/2012 (WP194)
//          https://ec.europa.eu/justice/article-29/documentation/opinion-recommendation/files/2012/wp194_en.pdf
//          *"쿠키가 여러 목적을 가지면 **모든 목적이 면제여야** 동의가 필요 없다."*
//
//     · 기기 목록  = 보안 쿠키 → **면제**
//     · 조회수 측정 = 자체 측정 → **면제라고 딱 잘라 말하기 어렵다**
//     → 섞여 있으면 **면제가 아닌 쪽으로 끌려간다.** 그래서 쪼갰다.
//
//   [★★ 왜 '면제'가 아니라 '동의'로 갔나]
//     프랑스 CNIL은 자체 측정 쿠키에 면제를 준다 — 단 조건이 붙는다:
//     1자사 전용 · 타사 미공유 · 프로파일링 없음 · 13개월 이하.
//     우리는 대부분 맞지만 **`post_views`가 "어떤 번호가 어떤 글을 봤나"를 7일 보관**한다.
//     그래서 *"개인과 연결되지 않는 집계"* 라고 단언하기 어렵다.
//     → **애매하면 물어본다.** 이 프로젝트의 기조("모르면 안 심는다")와 같은 판단이다.
//
//   [★ 거절하면 무엇이 달라지나 — '더 침해적인 쪽'으로 가지 않는다]
//     거절해도 조회수 중복 방지는 **접속지 지문**으로 계속한다. 다만 중요한 건 이것이다:
//       · **새로 심는 것이 없다.** IP는 어차피 요청마다 서버에 오는 값이다
//       · 원본이 아니라 지문만, 보관도 조회 기록과 같은 7일
//     → 거절은 *"기록을 남기지 마라"* 가 아니라 *"내 기기에 뭘 심지 마라"* 이고,
//       그 요구는 정확히 지켜진다.
//
//   [수명 — 목적에 딱 맞춘다]
//     판정 기준이 **"하루에 한 번"** 이므로 이 번호도 **하루면 충분하다.**
//     ★ WP194의 원칙이 그대로 적용된다 — *"수명은 그 목적에 직접 관계된 기간이어야 한다."*
//       (CNIL 면제 조건의 13개월보다도 훨씬 짧다)
// ============================================================

require_once __DIR__ . '/consent.php';

const VIEW_ID_COOKIE = 'viewer';
const VIEW_ID_DAYS   = 1;

function view_id_cookie_options(): array {
    return [
        'expires'  => time() + VIEW_ID_DAYS * 86400,
        'path'     => '/',
        'httponly' => true,      // JS가 만질 일이 없다
        'samesite' => 'Lax',
        'secure'   => !empty($_SERVER['HTTPS']),
    ];
}

// 이 브라우저의 조회 판정 번호. **동의하지 않았으면 null** — 그때는 아무것도 안 심는다.
//   ★ device_id()와 코드 모양은 같지만 **게이트가 하나 더 있다.**
//     같은 구조라도 무엇에 쓰이냐에 따라 물어봐야 하는지가 갈린다.
function view_id(): ?string {
    if (!has_consent('stats')) {
        return null;
    }

    $id = $_COOKIE[VIEW_ID_COOKIE] ?? '';

    if (!is_string($id) || !preg_match('/^[a-f0-9]{32}$/', $id)) {
        $id = bin2hex(random_bytes(16));
        setcookie(VIEW_ID_COOKIE, $id, view_id_cookie_options());
        // ★ 이 요청에서도 곧바로 쓰이게 채운다.
        //   안 채우면 첫 요청은 IP로, 둘째 요청부터는 번호로 판정돼 **한 사람이 두 번 세어진다.**
        //   (예전에 실제로 밟았던 함정이다)
        $_COOKIE[VIEW_ID_COOKIE] = $id;
    }

    return $id;
}
