<?php
// ============================================================
// session.php — 세션을 '켜는' 단 한 곳
//
//   [세션이 뭔가]
//     HTTP는 요청 하나하나가 서로를 기억하지 못한다. PHP 스크립트도 요청 한 번을
//     처리하고 죽어서, 변수는 그때 같이 사라진다.
//     세션 = 서버가 브라우저별로 값을 적어두는 '금고'다.
//       · 값은 서버 안에 있고,
//       · 브라우저에는 그 금고를 여는 '번호표'(쿠키 PHPSESSID)만 준다.
//
//   [왜 주소(?as=)보다 나은가]
//     주소에 실린 값은 사용자가 고칠 수 있다 → 남의 아이디를 적으면 그 사람이 됐다(사칭).
//     세션은 값이 서버에 있어서 사용자가 손댈 수 없다.
//     번호표를 위조해도 소용없다 — 서버가 발급한 적 없는 번호는 빈 금고를 열 뿐이다.
//     ★ 비유: 클럽 물품보관소. 짐은 카운터 안에 있고 나는 번호표만 들고 다닌다.
//
//   [왜 파일을 따로 뺐나]
//     session_start()는 '출력이 시작되기 전에, 딱 한 번' 불려야 한다.
//     화면 파일마다 흩어놓으면 반드시 어딘가를 빠뜨리거나 두 번 부르게 된다.
//     → 모든 페이지가 가장 먼저 부르는 util.php가 이 파일 하나를 부른다.
//       그래서 개별 화면은 세션을 '신경 쓸 필요조차' 없다.
// ============================================================

// 세션에 값을 넣을 때 쓰는 열쇠 이름.
//   ★ 문자열을 여기저기 직접 적지 않는다. 오타가 나면 '로그인이 안 된다'는 증상만 보이고
//     원인을 찾기가 아주 어렵다(오타는 그냥 '없는 값'으로 조용히 넘어가므로).
//   ★ 회원 '번호(id)'만 담는다. 닉네임·아바타까지 담으면, 설정에서 바꿔도
//     다시 로그인하기 전까지 옛날 값이 화면에 남는다. 나머지는 매 요청 DB에서 읽는다.
const SESSION_USER_ID = 'user_id';

// 이미 켜져 있으면 아무것도 하지 않는다.
//   require_once라 보통 한 번만 실행되지만, 두 번 부르면 PHP가 경고를 뱉으므로
//   '켜져 있는지 먼저 확인하고 켠다'(Tester-Doer).
if (session_status() === PHP_SESSION_NONE) {

    // ── 번호표(세션 쿠키)에 붙이는 안전장치 ──────────────────
    //   세션도 결국 쿠키 위에 올라탄다 — 번호표를 쿠키로 주고받기 때문이다.
    //   그래서 '번호표를 훔쳐가는 길'을 여기서 미리 막는다.
    session_set_cookie_params([
        // httponly = JS가 이 쿠키를 읽지 못하게 한다.
        //   글에 <script>가 하나라도 새어 들어가면(XSS) document.cookie로
        //   번호표를 통째로 훔쳐가 남의 계정에 들어갈 수 있다. 그 길을 끊는다.
        'httponly' => true,

        // samesite = 다른 사이트에서 시작된 요청에는 이 쿠키를 안 실어 보낸다.
        //   남의 사이트에 심어둔 <form>이 우리 서버로 POST를 쏘는 공격(CSRF)을 크게 줄인다.
        //   'Lax' = 링크를 눌러 들어오는 평범한 이동(GET)에는 실어 보낸다.
        //     ('Strict'로 하면 외부 링크로 들어올 때마다 로그아웃처럼 보여서 불편하다)
        'samesite' => 'Lax',

        // secure = https 연결에서만 쿠키를 보낸다.
        //   ★ 지금은 localhost(http)라 켜면 로그인 자체가 안 된다. 그래서 접속이
        //     https일 때만 자동으로 켜지게 했다. 실서비스는 항상 https이므로 항상 켜진다.
        'secure'   => !empty($_SERVER['HTTPS']),

        // path = 사이트 전체(/)에서 같은 세션을 쓴다.
        'path'     => '/',
    ]);

    // use_strict_mode = '서버가 발급한 적 없는 번호표'는 인정하지 않는다.
    //   [막는 공격 — 세션 고정(session fixation)]
    //     공격자가 피해자에게 자기가 정한 번호표를 미리 쥐여준다(예: 링크에 심어서).
    //     피해자가 그 번호표로 로그인하면, 같은 번호표를 가진 공격자도 함께 로그인된 상태가 된다.
    //   이 설정을 켜면 서버가 모르는 번호는 버리고 새로 발급한다 → 미리 쥐여주기가 통하지 않는다.
    //   (로그인하는 순간 번호표를 갈아 끼우는 session_regenerate_id와 짝을 이루는 방어다 — auth.php)
    ini_set('session.use_strict_mode', '1');

    // ── 세션을 '어디에' 저장할까 ─────────────────────────────
    //   PHP 기본값은 서버의 임시 파일이다 (/tmp/sess_4adbe17d…).
    //   그 자리를 DB 표(sessions)로 갈아 끼운다. 이유는 session_db.php 주석 참고.
    //   ★ 이 두 줄만 주석 처리하면 곧바로 원래(파일) 방식으로 돌아간다.
    //     저장 위치를 바꾸는 일이라, 되돌리는 길을 한 줄로 열어 두는 편이 안전하다.
    //   ★ 두 번째 인자 true = '요청이 끝날 때 세션을 저장하라'를 PHP에 미리 예약해 둔다.
    //     이걸 안 켜면 우리 핸들러가 쓰는 DB 연결이 먼저 정리돼 버려서,
    //     마지막 저장이 조용히 실패하는 일이 생긴다.
    require_once __DIR__ . '/session_db.php';
    session_set_save_handler(new DbSessionHandler(), true);

    // 여기서 실제로 켜진다. 이 줄 위로는 화면에 한 글자도 출력되면 안 된다
    //   (쿠키는 HTTP 헤더로 나가는데, 헤더는 본문보다 먼저 보내지기 때문).
    session_start();

    // ── 요청마다 번호표를 갈아 끼운다 ────────────────────────
    //   훔쳐간 번호표가 **주인의 다음 요청 한 번**이면 옛것이 되게 한다.
    //   자세한 이유와 한계는 session_db.php의 SESSION_GRACE 주석 참고.
    //
    //   ★ **로그인한 세션만** 회전시킨다.
    //     비로그인 세션을 훔쳐봐야 얻을 게 없고(담긴 건 CSRF 토큰과 조회 기록뿐),
    //     모든 방문자마다 돌리면 표에 행만 두 배로 쌓인다. **지킬 값이 있을 때만** 돈다.
    //
    //   ★ false = **옛 행을 지우지 말라**는 뜻. 지우면 겹친 요청이 다 죽는다.
    //     대신 바로 아래에서 수명을 30초로 줄여, 잠깐만 살아 있게 한다.
    //
    //   ★ 로그인·재인증 순간에는 auth.php가 session_regenerate_id(true)로 **즉시** 갈아 끼운다.
    //     거기서는 옛 번호표를 살려두면 안 된다 — **훔쳐간 쪽이 그 30초를 쓸 수 있기 때문**이다.
    //     같은 '회전'인데 **왜 도는지가 달라서** 옛것을 살리고 죽이고가 갈린다.
    if (!empty($_SESSION[SESSION_USER_ID])) {
        $previousId = session_id();
        session_regenerate_id(false);
        expire_session_soon($previousId);
    }
}
