<?php
// ============================================================
// settings/logout_others.php — 다른 기기에서 모두 로그아웃  [POST → PRG]
//
//   [무슨 기능인가]
//     PC방·남의 노트북에서 로그인해 두고 온 게 생각났을 때, 지금 이 기기에서
//     **다른 모든 기기의 로그인을 즉시 끊는다.** 구글·네이버 설정에 있는 그 기능이다.
//
//   [★ 왜 week16에서야 만들 수 있게 됐나]
//     끊어야 할 것이 두 군데인데, 지난주까지는 둘 다 손이 닿지 않았다:
//       ① 지금 켜져 있는 세션   — 세션이 '서버의 임시 파일'이면 남의 기기 파일을 찾을 수가 없다.
//                                 세션을 DB 표로 옮기고 user_id 칼럼을 두면서 가능해졌다.
//       ② '로그인 유지' 쿠키 표 — remember_tokens에 user_id가 있어서 원래 가능했다.
//     ★ 둘 중 하나만 지우면 **아무 효과가 없다.**
//       세션만 끊으면 다른 기기의 remember 쿠키가 다음 접속에 다시 로그인시키고,
//       표만 지우면 이미 열려 있는 세션은 그대로 살아 있다.
//
//   [지금 쓰는 기기는 왜 남기나]
//     "다른 기기에서 로그아웃"이 목적이지 내가 튕겨나가는 게 목적이 아니다.
//     내 세션까지 끊으면 버튼을 누른 사람이 로그인 화면으로 밀려나서, 정말 끊겼는지
//     확인할 방법도 없어진다.
// ============================================================
require_once __DIR__ . '/../includes/util.php';
require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../includes/remember.php';

require_login();

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    redirect('/settings/');
}

// ── 0-1) 우리 화면에서 온 요청이 맞나? (CSRF) ────────────────
//   ★ 이 액션은 특히 중요하다. 막지 않으면 남의 사이트가 우리 회원을
//     '모든 기기에서 로그아웃' 시키는 장난을 칠 수 있다(서비스 방해).
require_csrf();

$userId = current_user_id();

// ── ① 지금 켜져 있는 다른 세션을 끊는다 ─────────────────────
//   지금 쓰는 번호표(session_id())만 빼고 이 회원의 세션을 전부 지운다.
//   다른 기기는 다음 요청에서 '없는 번호표'가 되어 그 자리에서 로그아웃된다.
$closed = destroy_other_sessions($userId, session_id());

// ── ② '로그인 유지' 표를 전부 버리고, 이 기기 것만 다시 발급한다 ─
//   ①만 하면 다른 기기의 remember 쿠키가 살아 있어서 다음 접속에 되살아난다.
//   전부 버린 뒤, 이 기기가 원래 '로그인 유지'를 쓰고 있었다면 새 표를 다시 준다.
$hadRemember = isset($_COOKIE[REMEMBER_COOKIE]);
remember_forget_all($userId);
if ($hadRemember) {
    remember_issue($userId);
}

// ── ③ 알림 ──────────────────────────────────────────────────
//   끊은 개수를 알려준다. 0곳이면 '없었다'고 정확히 말한다 — 안 한 일을 한 척하지 않는다.
$message = $closed > 0
    ? "🔒 다른 기기 {$closed}곳에서 로그아웃했습니다."
    : '🔒 다른 기기에 로그인된 곳이 없었습니다.';
set_flash($message);

redirect('/settings/');
