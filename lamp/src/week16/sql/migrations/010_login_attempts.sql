-- ============================================================
-- 010_login_attempts.sql
--   로그인 실패를 기록해 **무차별 대입(brute force)** 을 막는다.
--
--   [무엇이 비어 있었나]
--     지금까지 만든 방어는 전부 **'훔친 열쇠'** 를 막는 것이었다 —
--     세션 고정 · CSRF · 탈취 · HTTPS.
--     그런데 **정문을 두드려 여는 것**은 아무도 안 막고 있었다.
--     비밀번호를 몇 번이든 틀려도 되니, 자동 스크립트면 짧은 비밀번호는 금방 뚫린다.
--
--   [★ 어디에 셀 것인가 — 또 하나의 '그릇 고르기']
--     · **세션**에 센다 → ❌ 브라우저(혹은 쿠키)만 바꾸면 0부터 다시. 공격자에게 무의미하다
--     · **쿠키**에 센다 → ❌ 사용자가 지우면 끝. 애초에 공격자 손에 있는 값이다
--     · **DB**에 센다   → ⭕ 유일하게 공격자가 못 건드리는 자리
--     ★ 이번 주차의 기준이 그대로 적용된다: **틀리면 손해 보는 값은 서버에.**
--       "몇 번 틀렸나"는 공격자가 0으로 되돌리고 싶은 값이므로 세션·쿠키에 두면 안 된다.
--
--   [★★ 무엇을 기준으로 셀 것인가 — 계정만 세면 안 된다]
--     "한 계정에 5번 실패하면 그 계정을 잠근다"가 가장 먼저 떠오르지만 함정이 있다:
--       **공격자가 남의 아이디를 일부러 5번 틀려서 그 사람을 잠글 수 있다.**
--       비밀번호를 모르는 채로 남을 못 들어오게 만드는 것 — 이것도 공격이다(계정 잠금 DoS).
--
--     → 그래서 **(아이디 + 접속지) 조합**으로 센다.
--       공격자가 자기 자리에서 남의 아이디를 두드려도 **막히는 건 공격자 자리**뿐이다.
--       진짜 주인은 다른 곳에서 접속하므로 멀쩡히 로그인된다.
--
--     → 그리고 **접속지 전체**도 따로 센다.
--       한 곳에서 아이디를 바꿔가며 훑는 공격(credential stuffing)은 위 조합에 안 걸리기 때문이다.
--
--   [★ IP를 여기서는 담는다 — consent_log와 반대 판단]
--     consent_log에서는 "증빙을 남기려고 개인정보를 더 모으면 본말전도"라며 IP를 뺐다.
--     여기서는 **IP가 방어의 축 자체**다. 목적이 다르면 판단도 달라진다.
--     ※ 다만 원본을 들고 있을 이유는 없다 — 우리가 하는 일은 '같은 곳인가' 비교뿐이므로
--       지문(SHA-256)만 담는다. 세션 ID를 지문으로 담는 것과 같은 이유다.
--
--   [보관 기간]
--     판정에 쓰는 창(15분)만 지나면 쓸모가 없다. 로그인할 때마다 오래된 줄을 지운다.
--     ★ consent_log와 정반대다 — 저건 **증빙**이라 영원히 쌓고, 이건 **판정용**이라 곧 버린다.
--       같은 '기록'이라도 **왜 남기는가**에 따라 수명이 갈린다.
-- ============================================================

CREATE TABLE IF NOT EXISTS login_attempts (
    id           BIGINT AUTO_INCREMENT PRIMARY KEY,

    -- 시도된 아이디. **없는 아이디여도 그대로 기록한다.**
    --   ★ 있는 것만 기록하면, 없는 아이디로 두드리는 정찰을 못 막는다.
    username     VARCHAR(50)  NOT NULL,

    -- 접속지 지문. 원본 IP는 담지 않는다 (비교만 하면 되므로).
    ip_hash      CHAR(64)     NOT NULL,

    attempted_at DATETIME     NOT NULL DEFAULT NOW(),

    -- 판정 쿼리가 쓰는 그대로 색인을 만든다.
    --   "이 접속지에서 최근 N분간" · "이 접속지 + 이 아이디로 최근 N분간"
    INDEX idx_attempt_ip   (ip_hash, attempted_at),
    INDEX idx_attempt_pair (ip_hash, username, attempted_at)

    -- ★ users로 가는 FOREIGN KEY를 걸지 않는다 —
    --   **없는 아이디로 온 시도도 기록해야 하기** 때문이다. 외래키를 걸면 그게 막힌다.
);
