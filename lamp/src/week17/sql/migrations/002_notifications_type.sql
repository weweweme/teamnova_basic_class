--   알림에 '종류'를 추가한다. 답글 알림이 생기면서 한 표에 두 종류가 섞이기 때문이다.
--
--   [왜 칼럼이 필요한가]
--     지금까지 알림은 '내 글에 댓글' 한 종류뿐이라, 화면 문구를
--     "…글에 댓글을 남겼어요"로 고정해 두어도 문제가 없었다.
--     여기에 '내 댓글에 답글'을 같은 표에 넣으면 그 문구가 거짓말이 된다.
--     → 무슨 알림인지를 행마다 적어두고, 화면이 그걸 보고 문구를 고른다.
--
--   [기존 351건은?]
--     DEFAULT 'comment' 이므로 전부 'comment'가 된다. 실제로 전부 댓글 알림이라 맞는 값이다.
-- ============================================================

-- comment = 내 글에 남이 댓글  /  reply = 내 댓글에 남이 답글
ALTER TABLE notifications
    ADD COLUMN IF NOT EXISTS type ENUM('comment','reply') NOT NULL DEFAULT 'comment' AFTER actor_id;
