-- ============================================================
-- 007_consent_log.sql
--   쿠키 동의 '증빙'을 남긴다.
--
--   [왜 쿠키만으로는 안 되나 — 이 표가 생긴 이유]
--     동의를 받았다는 사실을 **증명할 책임은 받은 쪽(우리)에** 있다.
--     그런데 쿠키는 사용자 브라우저에 있다:
--       · 사용자가 지울 수 있다        → 지우는 순간 우리 손에 아무것도 안 남는다
--       · 사용자가 만들 수도 있다      → 거꾸로 "동의했다"고 주장할 근거도 못 된다
--       · 기기마다 다르다              → 폰에서 동의해도 PC엔 없다
--     **증거는 증명하려는 사람 손에 있어야 한다.** 그래서 서버에도 남긴다.
--
--   [★ 쿠키를 없애는 게 아니다 — 역할이 갈린다]
--     · 쿠키 = **판단용 캐시.** "배너를 띄울까? 이 쿠키를 심어도 되나?"를 DB 왕복 없이 답한다
--     · 이 표 = **증빙 원본.** 지워지지 않고 쌓이기만 한다
--     같은 사실이 두 군데 있지만 하는 일이 다르다. 쿠키가 사라져도 사실은 안 사라진다.
--
--   [★★ 이 표는 '고치지 않는다' — append-only]
--     동의를 바꾸거나 철회해도 **기존 줄을 고치거나 지우지 않고 새 줄을 넣는다.**
--     "동의했다가 철회함"과 "동의한 적 없음"은 **다른 사실**이기 때문이다.
--     UPDATE로 덮어쓰면 그 차이가 사라져서, 나중에 무엇을 증명할 수가 없다.
--     → 그래서 기본키가 (사람)이 아니라 (사건 번호)다. 한 사람이 여러 줄을 갖는다.
--
--   [★★★ IP를 안 남긴다 — 일부러 뺐다]
--     실무에서는 IP를 함께 남기는 곳도 많다. 우리는 안 남긴다:
--       **증빙을 남기려고 개인정보를 더 모으면 본말이 전도된다.**
--     시각·브라우저·동의 식별자만으로도 "누가 언제 무엇에"는 충분히 특정된다.
--     (해시로 남기는 방법도 있지만, IPv4는 경우의 수가 43억뿐이라 되돌리기 쉬워 별 의미가 없다)
--
--   [비로그인은 어떻게 남기나]
--     배너는 로그인 안 한 사람에게도 뜬다. 그래서 무작위 **consent_id**를 만들어 쿠키에 넣고,
--     이 표는 그 번호로 기록한다. 나중에 로그인하면 'link' 줄을 한 줄 더 남겨 회원과 잇는다.
--     ★ 아이러니 하나 — **동의 기록을 남기려고 식별자를 만들면 그 식별자 자체가 수집이다.**
--       그래서 이것 말고는 아무것도 안 담는다. 뜻 없는 무작위 값 하나뿐이다.
-- ============================================================

CREATE TABLE IF NOT EXISTS consent_log (
    id             BIGINT AUTO_INCREMENT PRIMARY KEY,   -- 사건 번호. 시간순이 곧 이 순서다

    -- 누구의 브라우저인가. 무작위 32글자(16바이트) 16진수.
    --   ★ remember_tokens는 원본이 아니라 **지문(SHA-256)** 을 담는데 여기는 원본을 담는다.
    --     이유: remember 토큰은 **훔치면 계정이 넘어가는 열쇠**라 DB가 털려도 못 쓰게 해야 한다.
    --     consent_id는 열쇠가 아니다 — 훔쳐서 남의 것을 흉내 내봐야 **같은 동의 화면**을 볼 뿐이다.
    --     ★ 모양이 같다고 같은 처리를 하지 않는다. **무엇을 지키려는지**가 다르면 방식도 다르다.
    consent_id     CHAR(32)     NOT NULL,

    -- 로그인 상태에서 골랐으면 회원 번호. 비로그인이면 NULL.
    --   ★ NULL이 정상이다 — 동의는 로그인보다 먼저 받는다.
    user_id        INT          NULL,

    -- 무엇을 한 사건인가.
    --   grant  = 동의(또는 항목 변경)   revoke = 철회
    --   reset  = 선택 자체를 지움        link   = 로그인해서 회원과 이어짐
    action         VARCHAR(10)  NOT NULL,

    -- 어느 화면에서 골랐나. banner(배너) / settings(쿠키 설정 화면) / login(로그인 시 자동)
    --   ★ '어떻게 받았는가'는 증빙에서 반드시 묻는 것이다.
    source         VARCHAR(10)  NOT NULL,

    -- ★ 어떤 안내문에 동의했나. 이게 없으면 "저는 옛날 방침에만 동의했는데요"에 답할 수 없다.
    policy_version SMALLINT     NOT NULL,

    -- 무엇에 동의했나. {"view":1,"search":0} 모양.
    --   ★ 항목을 칼럼으로 만들지 않은 이유: 항목이 늘 때마다 표 구조를 바꿔야 하는데,
    --     그러면 **옛 줄에는 없던 칼럼이 생겨** 그때 무엇에 동의했는지가 흐려진다.
    --     '그 시점의 선택을 통째로 찍어두는' 편이 증빙에 맞다.
    items          VARCHAR(255) NOT NULL,

    -- 정황 증거. 어떤 브라우저에서 눌렀는가.
    user_agent     VARCHAR(255) NOT NULL DEFAULT '',

    created_at     DATETIME     NOT NULL DEFAULT NOW(),

    -- 이 브라우저의 이력을 시간순으로 꺼낼 때 쓴다.
    INDEX idx_consent_browser (consent_id, id),
    -- "이 회원이 언제 무엇에 동의했나"를 찾을 때 쓴다.
    INDEX idx_consent_user (user_id, id)

    -- ★ users로 가는 FOREIGN KEY를 일부러 안 건다.
    --   ON DELETE CASCADE면 **탈퇴하는 순간 증빙이 통째로 사라진다.** 그건 증빙이 아니다.
    --   (회원이 사라져도 "그때 동의를 받았다"는 사실은 남아야 한다)
);
