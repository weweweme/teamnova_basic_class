-- ============================================================
-- 004_remember_tokens.sql
--   '로그인 유지'(자동 로그인)용 표. week16 쿠키 주제.
--
--   [왜 필요한가]
--     세션은 브라우저를 닫으면 사라진다 — 그게 세션의 성질이다.
--     그런데 사용자는 "다음에 올 때도 로그인돼 있길" 바란다.
--     → 브라우저에 오래 남는 쿠키를 따로 주고, 그 쿠키로 세션을 되살린다.
--
--   [★ 쿠키에 무엇을 담나 — 여기가 핵심]
--     ❌ 아이디·비밀번호를 담으면 안 된다. 쿠키는 사용자 PC에 있어서 마음대로 고칠 수 있다.
--        week15의 ?as= 와 똑같은 실수가 된다.
--     ⭕ 추측 불가능한 '무작위 표'(토큰)를 만들어 쿠키에는 그 표만 담고,
--        서버는 표의 '지문'(해시)만 이 표에 보관한다.
--        → 쿠키를 고쳐봐야 우리 표에 없는 값이라 통과하지 못한다.
--
--   [왜 토큰을 그대로 저장하지 않고 해시로 저장하나]
--     DB가 통째로 유출됐을 때를 대비한다. 토큰이 그대로 적혀 있으면 유출된 순간
--     공격자가 그 값을 쿠키에 넣어 모든 계정에 들어갈 수 있다.
--     해시만 있으면 원래 토큰을 되돌릴 수 없으므로 쓸모가 없다.
--     (비밀번호를 password_hash로 저장하는 것과 같은 이유)
--
--   [왜 password_hash가 아니라 SHA-256인가]
--     비밀번호는 사람이 만들어서 '짧고 흔하다' → 일부러 느린 해시로 대입 공격을 막아야 한다.
--     토큰은 우리가 만든 32바이트 무작위값이라 애초에 대입이 불가능하다.
--     게다가 password_hash는 값마다 소금이 달라 '해시로 찾기'가 안 되고 전부 훑어야 한다.
--     → 여기서는 빠르고 찾기 쉬운 SHA-256이 맞다. (용도가 다르면 도구도 다르다)
-- ============================================================

CREATE TABLE IF NOT EXISTS remember_tokens (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    user_id    INT      NOT NULL,                 -- 누구의 표인가 → users.id
    token_hash CHAR(64) NOT NULL UNIQUE,          -- SHA-256을 16진수로 쓰면 항상 64글자 → CHAR(64)
                                                  --   UNIQUE = 같은 지문이 둘일 수 없다 + 찾기 빠른 색인이 자동으로 생긴다
    expires_at DATETIME NOT NULL,                 -- 이 시각이 지나면 무효 (기본 30일)
    created_at DATETIME DEFAULT NOW(),

    -- 회원이 사라지면 그 사람의 표도 함께 지운다.
    --   ★ 글·댓글이 참조하는 users는 RESTRICT(함부로 못 지우게)인데 여기는 CASCADE다.
    --     글은 '남겨야 할 내용물'이지만 이 표는 '로그인 부속물'이라 남길 이유가 없기 때문이다.
    --     알림(notifications)도 같은 이유로 CASCADE를 쓴다.
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
