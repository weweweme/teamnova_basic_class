-- ============================================================
-- 008_remember_series.sql
--   '로그인 유지' 표에 계열(series)을 붙여 **토큰 도난을 탐지**할 수 있게 한다.
--
--   [★ 지금까지 왜 탐지가 불가능했나 — 구조의 문제였다]
--     회전할 때 행을 **지우고 새로 만들었다**(DELETE + INSERT).
--     그러면 훔친 옛 토큰으로 접속했을 때 DB에 아무것도 안 남아 있어서,
--       · "옛날에 유효했던 토큰"인지
--       · "그냥 아무렇게나 지어낸 가짜"인지
--     구분할 방법이 없었다. 그냥 '없는 토큰'으로 무시했다.
--     그런데 앞의 것은 **명백한 도난 신호**다. 그 신호를 버리고 있었던 것이다.
--
--   [해결 — 계열(series)을 남긴다]
--     쿠키를 두 조각으로 나눈다:   series : token
--       · series = 이 **기기의 로그인 계열** ID. 회전해도 **안 바뀐다**
--       · token  = 접속할 때마다 새것으로 갈리는 값
--     회전은 이제 DELETE가 아니라 **token_hash만 UPDATE** 한다. 계열이 살아남는다.
--
--     그러면 판정이 셋으로 갈린다:
--       ① series ○ · token ○ → 정상. 토큰만 회전
--       ② series ○ · token ✗ → ★ **도난.** 같은 계열의 토큰이 두 갈래로 갈라졌다는 뜻
--       ③ series ✗           → 만료됐거나 위조. 조용히 무시
--
--   [★★ ②일 때 왜 '전부' 끊나 — 누가 진짜인지 알 수 없기 때문]
--     갈라졌다는 것만 알 뿐, 두 갈래 중 어느 쪽이 주인이고 어느 쪽이 도둑인지는 서버가 모른다.
--     한쪽만 살리면 **도둑을 살릴 수도 있다.** 그래서 둘 다 끊고 비밀번호를 다시 묻는 것이
--     유일하게 안전한 대응이다.
--
--   [★ selector : validator 라고 부르는 그 패턴이다]
--     series는 **평문으로 저장**한다 — 이건 '찾는 열쇠'일 뿐 비밀이 아니다.
--     token만 지문(SHA-256)으로 남긴다 — 이게 '증명하는 값'이다.
--     찾기(series)와 증명하기(token)를 나눠야 ②번 판정이 가능해진다.
--
--   [수명에 절대 상한을 둔다]
--     예전에는 회전할 때마다 expires_at을 '지금 + 30일'로 다시 썼다.
--     → **30일에 한 번만 들어와도 영원히 로그인 상태**였다. 상한이 없었던 것이다.
--     이제 issued_at(최초 발급)을 따로 두고, expires_at은 **회전해도 안 늘어난다.**
--     30일이 지나면 무조건 비밀번호를 다시 묻는다.
--     (NIST SP 800-63B는 단일 요소 인증의 재인증 상한을 30일로 본다)
-- ============================================================

-- 옛 표는 구조가 달라 이어 쓸 수 없다. 통째로 새로 만든다.
--   ★ 지우면 지금 '로그인 유지'를 켜둔 사람들이 한 번 더 로그인해야 한다.
--     자동 로그인은 편의 기능이라 이 정도 비용은 감수한다.
--     (반대로 글·댓글이었다면 절대 이렇게 하면 안 된다)
DROP TABLE IF EXISTS remember_tokens;

CREATE TABLE remember_tokens (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    user_id      INT      NOT NULL,             -- 누구의 표인가 → users.id

    -- 계열 ID. 쿠키의 앞 조각이고 **평문**이다. 회전해도 안 바뀐다.
    --   ★ UNIQUE라서 이걸로 행을 곧장 찾는다. 비밀이 아니므로 지문을 안 쓴다.
    series       CHAR(32) NOT NULL UNIQUE,

    -- 쿠키의 뒷 조각(token)의 지문. 접속할 때마다 새 값으로 바뀐다.
    --   ★ SHA-256으로 충분하다. 32바이트 무작위값이라 사전 공격 대상이 아니어서
    --     bcrypt 같은 '느린 해시'가 필요 없다. (비밀번호와 다른 점)
    token_hash   CHAR(64) NOT NULL,

    -- 최초 발급 시각. 회전해도 **안 바뀐다** → 절대 상한의 기준.
    issued_at    DATETIME NOT NULL,
    -- issued_at + 30일. 회전해도 **안 늘어난다.**
    expires_at   DATETIME NOT NULL,
    -- 마지막으로 쓰인 시각. 기기 목록에 "3일 전 사용"처럼 보여줄 때 쓴다.
    last_used_at DATETIME NULL,

    -- 어떤 브라우저인가. 정황 표시용이다.
    --   ★ 이 값으로 **판정하지 않는다.** user_agent는 사용자가 마음대로 보낼 수 있어
    --     방어에 못 쓴다. 게다가 브라우저 업데이트로도 바뀌어 오탐이 난다.
    user_agent   VARCHAR(255) NOT NULL DEFAULT '',

    -- '이 회원의 표 전부' 를 찾는 일이 잦다 (도난 탐지 시 일괄 폐기).
    INDEX idx_remember_user (user_id),

    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
