<?php
// ============================================================
// view_session.php — 조회 판정만 담는 **별도 세션**
//
//   [★ 왜 사용자 세션에 안 담나]
//     `$_SESSION`(PHPSESSID)에는 로그인·CSRF·도장 시계가 들어 있다.
//     거기에 조회 기록까지 넣으면 **매 요청 함께 읽히고 함께 커진다.**
//     그런데 조회 판정은 **글 보기 화면에서만** 필요하고, 수명도 다르다(하루).
//     → 담는 자리를 아예 나눈다.
//
//   [★ 왜 DB 표가 아니라 세션인가]
//     `post_views` 표로 만들었다가 지적을 받았다:
//       *"조회수 뻥튀기를 막는 기술에서, 블랙리스트를 만드는 기술로 넘어갔다."*
//     판정에 필요한 건 **"오늘 이 사람이 이 글을 봤나"** 하나뿐인데,
//     그걸 알자고 **누가 무엇을 봤는지를 서버가 한자리에 모으고** 있었다.
//     ★ 세션에 담으면 기록이 **그 사람 세션 안**에만 있다. 한자리에 모이지 않는다.
//
//   [★★ PHP는 세션을 여러 개 열 수 있다]
//     세션은 '이름'으로 갈린다. 이름을 바꿔 다시 열면 **쿠키도 저장분도 완전히 별개**다.
//       PHPSESSID    로그인 · CSRF · 도장 시계   (창을 닫으면 소멸)
//       VIEWSESSID   조회 판정만                 (하루)
//     한 요청에 하나만 열 수 있어서, 잠깐 바꿔 열고 **반드시 되돌려 놓는다.**
//
//   [★★ 그런데 '새 쿠키'를 주면 안 된다 — 여기서 한 번 틀렸다]
//     처음엔 `VIEWSESSID` 쿠키를 따로 심었다. 그런데 그건 앞뒤가 안 맞는다:
//       **그 쿠키만 지우면 조회수를 마음대로 부풀릴 수 있다.**
//     부풀리기를 막으려고 만든 장치가 **지우면 그만인 값**에 매달려 있는 셈이었다.
//
//     ★ 그래서 쿠키를 **하나도 안 만든다.** 대신 **이미 오는 값에서 번호를 계산**한다:
//       · 로그인했으면  회원 번호
//       · 아니면        **접속지(IP)**
//     같은 사람이면 **매 요청 같은 번호가 나오므로** 서버는 늘 같은 서랍을 연다.
//     → 브라우저는 이 세션의 존재조차 모른다. **지울 쿠키가 없다.**
//
//   [★★ 왜 쿠키가 아니라 접속지인가 — 지울 수 있으면 방어가 아니다]
//     한때 `device` 쿠키에서 번호를 뽑았다. 그런데 **쿠키를 지우면 새 서랍이 열려**
//     조회수를 얼마든지 부풀릴 수 있었다. 부풀리기를 막으려는 장치가
//     **지우면 그만인 값**에 매달려 있으면 방어라고 할 수 없다.
//
//     ★ 브라우저에 저장한 것은 **전부 지울 수 있다.** 지워도 알아보려면
//       **브라우저 밖의 값**이 필요하고, 남는 것은 접속지뿐이다.
//       (브라우저 지문 채취는 우리가 만든 쿠키 동의와 앞뒤가 안 맞아 안 쓴다)
//     ※ Discourse도 같다 — 로그인은 회원 번호, 아니면 IP로 판정한다.
//
//   [★ 접속지를 어디에도 저장하지 않는다]
//     IP는 **번호를 계산하는 데만** 쓰고 그 자리에서 버린다. 칼럼으로 담지 않는다.
//     → SQL로 *"이 접속지가 본 글 전부"* 를 뽑을 수 없다.
//     한 번 뒤섞어 담는 이유도 같다 — 세션 표에 접속지가 **그대로 찍히지 않게** 한다.
//     (완전한 방어는 아니다. 아래 view_session_id() 주석에 한계를 적어뒀다)
//
//   [내준 것 — 정확도]
//     · 같은 공유기 뒤(집·회사·학교)는 **통째로 한 명**이 된다        → 과소 집계
//     · 모바일은 접속지가 자주 바뀌어 **같은 사람이 여러 명**이 된다   → 과대 집계
//     ★ **부풀리기를 막는 것과 정확히 세는 것을 저울에 올려, 막는 쪽을 골랐다.**
// ============================================================

require_once __DIR__ . '/session.php';    // 사용자 세션이 이미 열려 있다는 전제
require_once __DIR__ . '/auth.php';       // is_logged_in() · current_user_id()
require_once __DIR__ . '/session_db.php'; // VIEW_SESSION_NAME · VIEW_SESSION_DAYS

// 이 사람의 판정 서랍 번호. **매 요청 같은 값이 나온다.**
//   ★ 쿠키로 받지 않고 **서버가 계산한다.** 그래서 브라우저가 지울 수 없다.
function view_session_id(): string {
    $seed = is_logged_in()
        ? 'u:' . current_user_id()                          // 회원이면 브라우저가 바뀌어도 같은 서랍
        : 'ip:' . ($_SERVER['REMOTE_ADDR'] ?? '');          // 아니면 접속지 — 쿠키를 지워도 그대로다

    // 한 번 뒤섞어서 담는다 — **접속지가 그대로 세션 번호가 되지 않게.**
    //   ⚠️ 다만 이건 '가리기'지 '지키기'가 아니다. IPv4는 43억뿐이라
    //     마음먹고 전부 해시해 보면 되짚을 수 있다. 진짜로 막으려면
    //     **서버에만 있는 비밀값**을 함께 섞어야 하는데, 이 프로젝트엔 그런 값이 없다.
    return hash('sha256', 'view-session|' . $seed);
}
// ★★ 서랍에 담는 모양 — **날짜는 서랍 전체에 하나, 칸에는 글 번호만.**
//   처음엔 칸마다 날짜를 적었다(`글번호 → "2026-08-19"`). 두 가지가 잘못됐었다:
//     ① **어제 날짜가 적힌 칸이 오늘 자리를 차지한다.** 판정은 '오늘인가'로 하므로
//        어제 칸은 절대 안 걸리는 **죽은 칸**인데, 상한은 그대로 잡아먹었다.
//        → 어제 40개를 봤으면 오늘은 10칸뿐. **상한이 정해도 실효 용량은 매일 달랐다.**
//     ② **같은 날짜를 칸마다 반복해 적었다.** 실측 80바이트 중 54바이트(67%)가
//        똑같은 문자열의 반복이었다. 한 사람의 서랍이니 한 번만 적으면 된다.
//   → 날짜를 위로 빼고, 날짜가 바뀌면 **통째로 비운다.**
//     죽은 칸이 존재할 수 없게 되고, 1칸이 23바이트 → **9바이트**(`i:23;b:1;`)가 된다.
const VIEWED_ON_KEY     = 'on';          // 이 서랍이 **어느 날짜의 것인가** (하나뿐)
const VIEWED_POSTS_KEY  = 'seen';        // 그날 본 글 번호들. 세션 최상위 키는 **문자열**이어야 한다

// ★★ 개수 상한을 두지 않는다.
//   한때 50칸으로 잘랐다가 걷어냈다. 상한이 있으면 **밀려난 글이 오늘 다시 세어진다** —
//   조회수 부풀리기를 막으려고 만든 장치에 "N번째부터는 안 막힘"이 들어 있는 셈이었다.
//   판정이 정확해야 하는 장치에서 정확도를 깎는 상한은 있을 이유가 없다.
//
//   ★ 그럼 커지는 건 어떻게 감당하나 — **그건 저장소가 감당할 문제다.**
//     1칸이 약 9바이트(`i:23;b:1;`)라 글 1,000개를 봐도 10KB 남짓이고,
//     `sessions.payload`를 MEDIUMTEXT(16MB)로 넓혀 뒀다(019 마이그레이션).
//     그래도 모자라면 **칼럼을 더 넓히거나 장비를 늘릴 일**이지,
//     판정 로직이 사용자를 잘라낼 일이 아니다.
//   ※ 참고: Spring + Redis 세션 구현들도 `HashSet<Long>`에 상한을 두지 않는다.

// 판정 세션을 잠깐 열어 $work 를 실행하고, **원래 세션으로 되돌려 놓는다.**
//   ★ 되돌리는 것이 이 함수의 핵심이다. 안 되돌리면 그 뒤 요청 처리가 통째로
//     엉뚱한 세션을 보게 되어 로그인 상태가 사라진 것처럼 보인다.
function with_view_session(callable $work): mixed {
    $mainName = session_name();
    $mainId   = session_id();            // ★ 번호까지 기억해야 되돌릴 수 있다
    $wasOpen  = session_status() === PHP_SESSION_ACTIVE;

    // 잠깐 바꿀 설정들. 끝나고 그대로 되돌린다.
    $strictMode  = ini_get('session.use_strict_mode');
    $useCookies  = ini_get('session.use_cookies');
    $gcMaxLife   = ini_get('session.gc_maxlifetime');

    // 한 요청에 세션은 하나만 열린다 → 사용자 세션을 먼저 닫는다.
    if ($wasOpen) {
        session_write_close();
    }

    // ★ 쿠키를 아예 안 쓴다. 번호를 우리가 계산하므로 브라우저에 줄 것이 없다.
    //   ⚠️ `use_only_cookies`는 건드리지 않는다 — PHP 8.5에서 끄는 것이 폐기 예정이라
    //     **경고가 출력을 시작해** 뒤따르는 session_start()가 통째로 실패한다. (실제로 밟음)
    //     어차피 번호를 우리가 넣으므로 그 설정은 판정에 영향이 없다.
    ini_set('session.use_cookies', '0');

    // ★ 엄격 모드는 "서버가 발급한 적 없는 번호는 거부"하는 장치다.
    //   그건 **사용자가 번호를 들고 올 때** 필요한 방어인데, 여기서는 서버가 계산한다.
    //   켜두면 우리가 만든 번호마저 거부당해 **매번 새 서랍이 열린다.**
    ini_set('session.use_strict_mode', '0');

    ini_set('session.gc_maxlifetime', (string) (VIEW_SESSION_DAYS * 86400));

    session_name(VIEW_SESSION_NAME);
    session_id(view_session_id());
    session_start();

    try {
        return $work();
    } finally {
        // ★ finally — 중간에 예외가 나도 **반드시** 원래 세션으로 되돌린다.
        session_write_close();

        ini_set('session.use_strict_mode', (string) $strictMode);
        ini_set('session.use_cookies', (string) $useCookies);
        ini_set('session.gc_maxlifetime', (string) $gcMaxLife);

        session_name($mainName);
        session_id($mainId);
        if ($wasOpen) {
            session_start();
        }
    }
}

// 오늘 이 사람이 이 글을 이미 봤나? 안 봤으면 **봤다고 적고** false를 돌려준다.
//   ★ '확인'과 '적기'를 한 함수에서 함께 한다 — 나누면 그 사이에 끼어들 틈이 생기고,
//     부르는 쪽이 적는 것을 빠뜨릴 수 있다.
function view_already_counted_today(int $postId, string $today): bool {
    return (bool) with_view_session(static function () use ($postId, $today): bool {
        // ★ 하루 경계가 **여기 한 곳**이다. 날짜가 바뀌었으면 어제 것을 통째로 버린다.
        //   ⚠️ 세션 만료에 기대지 않는다 — 그러면 "언제 다시 셀지"를 우리가 정한 게 아니라
        //     세션 설정이 우연히 정하게 된다. 실제로 한 번 그렇게 되어 있었다.
        if (($_SESSION[VIEWED_ON_KEY] ?? null) !== $today) {
            $_SESSION[VIEWED_ON_KEY]    = $today;
            $_SESSION[VIEWED_POSTS_KEY] = [];
        }

        // ★★ 글 번호를 세션의 **최상위 키로 쓰면 안 된다.**
        //   PHP의 기본 세션 직렬화는 `이름|값` 꼴이라 **최상위 키가 문자열이어야** 하고,
        //   숫자 키는 저장할 때 **조용히 버려진다.** (경고만 뜨고 값이 안 남는다)
        //   → 한 칸 안에 배열로 담는다. 배열 **안쪽** 키는 숫자여도 괜찮다.
        $seen = $_SESSION[VIEWED_POSTS_KEY] ?? [];
        if (!is_array($seen)) {
            $seen = [];                   // 값이 깨졌으면 버리고 새로 센다
        }

        // ★ 담긴 것이 전부 '오늘 본 글'이므로, **있으면 봤다**로 끝난다.
        //   값은 볼 필요가 없어서 `true` 한 글자만 넣는다(`b:1;` — 4바이트).
        if (isset($seen[$postId])) {
            return true;
        }
        $seen[$postId] = true;

        $_SESSION[VIEWED_POSTS_KEY] = $seen;

        return false;
    });
}
