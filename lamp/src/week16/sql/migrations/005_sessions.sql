-- ============================================================
-- 005_sessions.sql
--   세션을 '서버의 임시 파일'이 아니라 'DB 표'에 저장한다. week16 쿠키·세션 주제.
--
--   [지금까지는 어디에 있었나]
--     PHP 기본값은 서버의 임시 파일이다 — /tmp/sess_1a3de09858f12e... 같은 파일 하나가
--     세션 하나다. 파일 이름 뒤쪽이 곧 브라우저가 들고 있는 번호표(PHPSESSID)다.
--
--   [왜 DB로 옮기나 — 이유 셋]
--     ① 서버를 여러 대로 늘리면 파일은 공유가 안 된다.
--        1번 서버에서 로그인했는데 다음 요청이 2번 서버로 가면 "누구세요?"가 된다.
--        (실무에서 세션을 Redis나 DB로 옮기는 첫 번째 이유가 이것이다)
--     ② '이 회원의 세션을 전부 끊어라'를 할 수 있게 된다.
--        파일 방식으로는 남의 기기 세션 파일을 찾을 방법이 없다.
--        → user_id 칼럼이 있어서 WHERE user_id = ? 한 줄이면 된다. ('모든 기기에서 로그아웃')
--     ③ 눈으로 볼 수 있다. 세션이 추상적인 개념이 아니라 표의 행이 된다.
--
--   [★ 왜 세션 ID를 그대로 안 넣고 해시로 넣나]
--     세션 ID는 '지금 로그인한 상태' 그 자체다. 이 값을 아는 사람은 곧 그 사람이 된다.
--     DB가 통째로 유출되면, 원본이 적혀 있을 경우 그 값을 쿠키에 넣어 남의 계정에 들어갈 수 있다.
--     지문(SHA-256)만 있으면 원래 값을 되돌릴 수 없으므로 쓸모가 없다.
--     → remember_tokens와 완전히 같은 방침이다. '서버가 들고 있는 건 언제나 지문'.
--     ※ Django·Laravel의 기본값은 원본 저장이다. 우리는 한 단계 더 조인 쪽을 골랐다.
--
--   [왜 remember_tokens와 한 표로 합치지 않나]
--     수명과 주인이 다르다.
--       · 세션      = '지금 이 방문'.  비로그인 방문자에게도 생긴다(user_id가 NULL).
--       · remember  = '다음에 또 올게'. 로그인한 사람만, 30일.
--     한 표에 섞으면 만료 정책도 조회 조건도 매번 갈라 써야 한다.
-- ============================================================

CREATE TABLE IF NOT EXISTS sessions (
    -- 세션 ID의 지문. SHA-256을 16진수로 쓰면 항상 64글자 → CHAR(64).
    --   기본키로 두는 이유: 세션은 '번호로 딱 하나 찾기'가 거의 전부라서,
    --   찾는 열쇠 자체를 기본키로 두면 색인이 따로 필요 없다.
    id_hash     CHAR(64) PRIMARY KEY,

    -- 누구의 세션인가. 로그인 안 한 방문자도 세션을 갖기 때문에 NULL을 허용한다.
    --   ★ 이 값은 payload 안에도 들어 있다. 그런데도 칼럼으로 따로 꺼내 두는 이유:
    --     payload는 통째로 직렬화된 덩어리라 SQL로 뒤질 수가 없다.
    --     밖으로 꺼내 둬야 WHERE user_id = ? 로 '이 사람의 세션 전부'를 찾을 수 있다.
    user_id     INT          NULL,

    -- 세션에 담긴 내용. PHP가 직렬화한 문자열이 그대로 들어간다.
    --   예: user_id|i:8;csrf_token|s:64:"8965…";flash|a:4:{…}
    payload     TEXT         NOT NULL,

    -- 어디서 접속했나. 세션 자체에는 필요 없지만, '내 로그인 기기 목록' 같은 화면을
    --   만들 때 쓰인다. Laravel의 sessions 표도 이 두 칸을 갖는다.
    ip_address  VARCHAR(45)  NULL,             -- IPv6까지 담으려면 45글자가 필요하다
    user_agent  VARCHAR(255) NULL,

    -- 마지막으로 이 세션을 쓴 시각. 새로고침할 때마다 갱신된다.
    last_active DATETIME     NOT NULL,

    -- 이 시각이 지나면 무효. 청소(gc)도 이 칼럼을 기준으로 지운다.
    --   ★ 쿠키의 만료와 별개로 서버에도 만료를 둔다 — 쿠키 만료는 브라우저가 지키는
    --     약속이라 사용자가 늘릴 수 있기 때문. 진짜 기준은 언제나 서버 쪽이다.
    expires_at  DATETIME     NOT NULL,

    created_at  DATETIME     DEFAULT NOW(),

    -- 만료된 행을 지우는 청소 작업이 이 칼럼으로 훑으므로 색인을 둔다.
    INDEX idx_sessions_expires (expires_at),

    -- 회원이 사라지면 그 사람의 세션도 함께 지운다. (로그인 부속물이므로 CASCADE)
    --   ※ user_id가 NULL인 행(비로그인 방문자)은 외래키 제약을 받지 않는다.
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
