<?php
// ============================================================
// csrf.php — CSRF(위조 요청) 방어
//
//   [무슨 공격인가]
//     CSRF = Cross-Site Request Forgery, '다른 사이트에서 요청을 위조한다'는 뜻.
//     내가 우리 사이트에 로그인해 둔 상태에서, 전혀 다른 사이트의 페이지를 열었다고 하자.
//     그 페이지에 이런 게 숨어 있다면:
//
//       <form action="http://우리사이트/post/delete.php" method="post">
//         <input type="hidden" name="id" value="123">
//       </form>
//       <script>document.forms[0].submit()</script>   ← 열자마자 자동 전송
//
//     브라우저는 우리 사이트로 요청을 보내면서 **쿠키(세션 번호표)를 자동으로 같이 보낸다.**
//     서버 입장에서는 로그인한 본인이 삭제 버튼을 누른 것과 구분이 안 된다. 그대로 지워진다.
//
//   ★ 핵심: 이 공격은 '로그인을 뚫는' 게 아니다. 이미 로그인된 나를 **시켜먹는** 것이다.
//     그래서 비밀번호를 아무리 길게 해도 막히지 않는다.
//     비유: 남이 내 도장을 훔친 게 아니라, 나를 속여서 내 손으로 도장을 찍게 만든 것.
//
//   [어떻게 막나 — 추측할 수 없는 표]
//     우리 서버가 화면을 그릴 때, 폼 안에 아무도 못 맞히는 무작위 문자열(토큰)을 숨겨 둔다.
//     그리고 요청을 받을 때 "이 토큰, 내가 발급한 게 맞나"를 대조한다.
//     공격자의 페이지는 우리 서버가 그린 게 아니므로 그 값을 알 수 없다 → 대조에서 걸린다.
//     ※ 공격자가 우리 사이트를 열어 토큰을 훔쳐볼 수도 없다. 브라우저의 '동일 출처 정책'이
//       다른 사이트의 응답 내용을 JS로 읽는 것을 막기 때문이다.
//     비유: 놀이공원 손목띠. 입구에서 받은 오늘자 띠가 없으면 놀이기구를 못 탄다.
//
//   [★ 왜 week16에 와서야 만드나]
//     정답(발급한 토큰)을 **서버가 어딘가에 적어둬야** 대조할 수 있다.
//     week15는 서버가 요청 사이에 아무것도 기억하지 않았다 → 발급한 사실 자체를 적을 데가
//     없어서 이 방어를 시작조차 못 했다. 세션이 생겨서 비로소 가능해진 것이다.
//
//   ※ session.php에서 켠 세션 쿠키의 SameSite=Lax 도 같은 공격을 상당 부분 막는다.
//     그래도 토큰을 다는 이유: SameSite는 '브라우저가 지켜주는' 방어라 낡은 브라우저나
//     예외 상황에서 뚫린다. 서버가 스스로 확인하는 쪽이 진짜 방어다. (다층 방어)
// ============================================================

require_once __DIR__ . '/session.php';   // 토큰을 세션에 보관하므로

// 세션에 토큰을 넣을 때 쓰는 열쇠 이름.
const SESSION_CSRF = 'csrf_token';

// 폼에 심을 hidden 필드의 이름. 서버가 받을 때도 이 이름으로 꺼낸다.
//   앞에 _ 를 붙여 우리 데이터(title·content…)와 눈으로 구분되게 했다.
const CSRF_FIELD = '_token';

// 이번 방문에 쓸 토큰. 없으면 새로 만들어 세션에 넣는다.
//   ★ 세션당 하나만 만들어 계속 쓴다. 폼마다 새로 만드는 방식도 있지만,
//     탭을 여러 개 열어두면 먼저 연 탭의 토큰이 무효가 돼 멀쩡한 제출이 거부된다.
function csrf_token(): string {
    if (empty($_SESSION[SESSION_CSRF])) {
        // random_bytes = 암호학적으로 안전한 무작위 바이트.
        //   ★ rand()·mt_rand()를 쓰면 안 된다. 그건 '재현 가능한' 난수라
        //     값 몇 개를 보면 다음 값을 계산해낼 수 있다. 토큰은 추측 불가가 생명이다.
        //   32바이트 = 256비트. bin2hex로 사람이 읽을 수 있는 16진수 64글자로 바꾼다.
        $_SESSION[SESSION_CSRF] = bin2hex(random_bytes(32));
    }
    return $_SESSION[SESSION_CSRF];
}

// 폼 안에 넣을 hidden 필드 HTML을 만든다.
//   쓰는 법: POST 폼의 여는 태그 바로 다음 줄에서 이 함수를 출력한다.
//     실제 예는 includes/header.php의 로그아웃 폼, post/view.php의 댓글 폼 등에 있다.
//   ※ 여기에 코드 예시를 그대로 못 적는 이유가 있다 — PHP는 // 주석 안에서도
//     '태그 닫기' 기호를 만나면 거기서 PHP 모드를 끝내버린다. 주석 안에 적었다가
//     이 파일 아래쪽이 통째로 화면에 글자로 쏟아진 적이 있다. (실제로 겪은 함정)
//   ★ 결과는 '이미 안전 처리된 HTML'이므로 화면에서 e()를 한 번 더 씌우지 않는다.
//     (create_highlighted()와 같은 규칙. 이름이 create_… 가 아닌 이유는
//      매번 같은 토큰을 담은 같은 문자열이기 때문이다)
function csrf_field(): string {
    return '<input type="hidden" name="' . CSRF_FIELD . '" value="' . e(csrf_token()) . '">';
}

// 이 요청이 '우리 화면에서 출발한 것'인지 확인한다. 아니면 거부하고 홈으로 보낸다.
//   ★ POST를 처리하는 파일이라면 예외 없이 전부 부른다.
//     한 곳이라도 빠지면 그 파일이 통째로 공격 통로가 된다.
function require_csrf(): void {
    $sent = post_str(CSRF_FIELD);
    $real = $_SESSION[SESSION_CSRF] ?? '';

    // hash_equals = 두 문자열이 같은지 확인하되, '항상 같은 시간'이 걸리게 비교한다.
    //   왜 === 를 안 쓰나: === 는 다른 글자를 만나는 순간 즉시 멈춘다. 그래서 첫 글자가
    //   맞을 때가 틀릴 때보다 아주 조금 더 오래 걸린다. 그 시간차를 수만 번 재서
    //   토큰을 한 글자씩 알아내는 공격(타이밍 공격)이 실제로 있다.
    //   이 함수는 끝까지 다 비교하므로 시간차가 안 생긴다.
    if ($real === '' || !hash_equals($real, $sent)) {
        set_flash('⚠️ 잘못된 요청입니다. 다시 시도해 주세요.', 'error');
        redirect('/');
    }
}
