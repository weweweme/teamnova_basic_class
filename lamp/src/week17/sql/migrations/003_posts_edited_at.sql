-- ============================================================
-- 003_posts_edited_at.sql
--   글에도 '수정한 시각'을 남긴다. 댓글(001)에 넣은 edited_at의 글 버전.
--
--   [왜 필요한가]
--     지금은 글을 고쳐도 화면에 아무 표시가 없다.
--     글을 올려 반응을 받은 뒤 내용을 슬쩍 바꿔도 읽는 사람은 알 수 없다는 뜻이다.
--     댓글에는 이미 '(수정됨)'이 붙는데 글에는 없어서 서로 어긋나 있기도 했다.
--
--   [기존 180개 글은?]
--     DEFAULT NULL 이므로 '한 번도 안 고침'으로 남는다. 실제로 그렇다.
-- ============================================================

-- 수정한 시각. NULL이면 한 번도 안 고친 글 → 화면의 '(수정됨)' 표시에 쓴다.
ALTER TABLE posts
    ADD COLUMN IF NOT EXISTS edited_at DATETIME DEFAULT NULL AFTER created_at;
