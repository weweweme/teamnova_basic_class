-- 013_post_views_ip.sql
--   조회 기록에 **접속지 지문**을 더한다. 쿠키를 지워도 하루 1회를 지키기 위해서다.
--
--   [왜 필요해졌나 — 조회수가 첫 화면을 결정하기 때문]
--     조회수는 그냥 표시되는 숫자가 아니다. 네 곳을 움직인다:
--       · 홈 '지금 뜨는 글'(최근 7일 조회순)  · 게시판 '조회' 탭
--       · 게시판 '인기' 탭 · 랭킹 화면
--     즉 **부풀리면 첫 화면에 올라간다.** 부풀릴 이유가 실제로 있는 것이다.
--
--     게다가 '지금 뜨는 글'을 **최근 7일** 기준으로 바꾸면서 이 구멍이 커졌다 —
--     누적 5,000짜리 글을 이기려면 5,000번이 필요했는데, 이제 **열 번이면 1등**이다.
--     ★ 개선 하나가 다른 쪽 구멍을 키운 것이다.
--
--   [★ 무엇을 막나 — 쿠키를 지우는 것]
--     지금 판정 키는 device 쿠키다. **쿠키를 지우거나 시크릿 창을 열면** 새 번호가 생겨
--     같은 사람이 몇 번이든 셀 수 있었다.
--     → 쿠키가 **없던 상대**에 한해 "이 접속지가 오늘 이 글을 이미 봤나"를 함께 본다.
--
--   [★★ 오탐을 어디까지 감수하나 — 경계를 좁게 잡았다]
--     IP는 공유된다(회사망·공용 와이파이). 그래서 Discourse처럼 **항상** IP로 판정하면
--     같은 건물 사람들이 통째로 한 명이 된다.
--     우리는 **쿠키가 없던 첫 요청에만** 이 검사를 건다:
--       · 쿠키 지우고 재방문 → 같은 IP가 오늘 이미 봄 → **막힌다** ✅
--       · 공유 IP의 다른 사람 → **자기가 처음 여는 글 하나만** 안 세어진다.
--         그 뒤로는 쿠키가 생겨 정상 판정된다 (Discourse보다 오탐이 좁다)
--
--   [★ 로그인 사용자의 IP는 담지 않는다]
--     회원 번호로 이미 정확히 판정되므로 IP가 필요 없다.
--     **필요 없는 개인정보는 애초에 안 모은다** — Discourse도 소스에 같은 주석이 있다
--     ("do not store IP of logged in users").
--     ※ 원본이 아니라 지문(SHA-256)만 담는다. 우리가 하는 일은 '같은 곳인가' 비교뿐이다.
--     ※ 보관 기간은 조회 기록과 같다(7일). 판정에 안 쓰이면 함께 지워진다.
-- ============================================================

ALTER TABLE post_views ADD COLUMN ip_hash CHAR(64) NULL AFTER viewer_key;

-- "이 접속지가 오늘 이 글을 봤나"를 한 번에 찾기 위한 색인.
ALTER TABLE post_views ADD INDEX idx_post_views_ip (post_id, ip_hash, viewed_on);
