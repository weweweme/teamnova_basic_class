-- 011_user_devices.sql
--   '로그인한 기기' 목록을 **세션과 분리된 표**로 만든다.
--
--   [★ 왜 sessions 표에서 뽑으면 안 되나 — 두 가지를 혼동했었다]
--     처음엔 `sessions`를 그대로 보여줬다. 세션 한 줄 = 기기 하나로 본 것이다.
--     그런데 **세션과 기기는 성격이 완전히 다르다**:
--
--       · 세션   = **'지금 이 방문'.**   30분이면 죽는다. 요청마다 읽고 쓰는 뜨거운 값
--       · 기기   = **'회원의 기록'.**    로그아웃해도 남아야 한다. 가끔 보는 차가운 값
--
--     그래서 sessions 기반 목록에는 결정적인 구멍이 있었다:
--       ① **만료되면 목록에서 사라진다** — "지난주 PC방에서 로그인한 걸 끊고 싶다"가
--          정작 안 된다. 그 세션은 이미 죽어서 목록에 없기 때문이다.
--          **기기 목록의 가장 큰 용도가 바로 그건데** 그걸 못 했다.
--       ② **번호표 회전과 충돌한다** — 요청마다 id_hash가 바뀌므로, 목록의 한 줄이
--          매번 다른 것을 가리키고 [로그아웃] 버튼이 실어 보낸 지문은 누르는 순간 옛것이다.
--
--   [★★ 우리 기준을 다시 대보면 답이 나온다 — "이 값의 주인이 누구인가"]
--     · 주인이 **브라우저** → 쿠키   (취향·최근 본 글)
--     · 주인이 **이 방문**  → 세션   (신원·CSRF·조회 기록)
--     · 주인이 **회원**     → DB 표  ← **기기 목록이 여기다**
--     기기 기록은 세션이 죽어도, 브라우저를 닫아도 남아야 한다. 그러므로 표가 맞다.
--
--   [실무가 이렇게 하는 이유이기도 하다]
--     트래픽이 큰 곳은 세션을 Redis에 둔다(TTL 내장 · 빠름). 그러면 sessions 표 자체가 없다.
--     그래도 '내 기기 목록'은 멀쩡히 동작한다 — **애초에 다른 표에 있기 때문**이다.
--     → 이 구조는 **세션 저장소가 무엇이든 상관없다.**
--
--   [기기를 어떻게 알아보나]
--     오래 사는 무작위 값을 쿠키에 심고, 그 값으로 같은 기기를 알아본다.
--     ★ consent_id와 **완전히 같은 구조**다 — 쿠키엔 뜻 없는 열쇠, 내용은 전부 서버에.
--     ※ 훔쳐가 봐야 '기기 이름표'일 뿐이라 지문이 아니라 원본을 담는다(= consent_id와 같은 판단).
--
--   [★ 그리고 세션에도 device_id를 붙인다]
--     기기를 끊을 때 **그 기기의 세션까지 끊어야** 실효가 있다.
--     표만 지우면 이미 열려 있는 창은 멀쩡히 살아 있다. (로그아웃에서 밟았던 그 함정)
-- ============================================================

CREATE TABLE IF NOT EXISTS user_devices (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    user_id       INT      NOT NULL,          -- 누구의 기기인가 → users.id

    -- 브라우저에 심어둔 무작위 기기 번호(32글자). 쿠키의 값과 같다.
    device_id     CHAR(32) NOT NULL,

    -- 어떤 브라우저인가. **표시용일 뿐 판정에 쓰지 않는다** —
    --   user_agent는 사용자가 마음대로 보낼 수 있고, 브라우저 업데이트로도 바뀐다.
    user_agent    VARCHAR(255) NOT NULL DEFAULT '',

    first_seen_at DATETIME NOT NULL DEFAULT NOW(),   -- 이 기기로 처음 로그인한 때
    last_login_at DATETIME NOT NULL DEFAULT NOW(),   -- 마지막으로 로그인한 때

    -- 주인에게 "새 기기에서 로그인됐다"를 알렸는가.
    --   ★ 0인 채로 남아 있으면, 주인이 **어느 기기로 접속하든** 한 번 알려준다.
    --     알림을 '그 기기'로 보내면 의미가 없다 — 정작 알아야 할 사람은 **주인**이다.
    announced     TINYINT(1) NOT NULL DEFAULT 0,

    -- 한 회원의 같은 기기는 한 줄. 다시 로그인하면 새 줄이 아니라 갱신이다.
    UNIQUE KEY uniq_user_device (user_id, device_id),
    INDEX idx_device_user (user_id, last_login_at),

    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 세션이 '어느 기기의 것인지' 적어둔다.
--   ★ 이게 있어야 기기를 끊을 때 그 기기의 세션까지 함께 끊을 수 있다.
--     (payload 안에 넣으면 직렬화된 덩어리라 SQL로 못 찾는다 — user_id를 칼럼으로 뺀 것과 같은 이유)
ALTER TABLE sessions ADD COLUMN device_id CHAR(32) NULL AFTER user_id;
ALTER TABLE sessions ADD INDEX idx_sessions_device (user_id, device_id);
