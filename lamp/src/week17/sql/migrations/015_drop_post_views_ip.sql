-- 015_drop_post_views_ip.sql
--   `post_views.ip_hash` 를 없앤다. **판정 키 자체가 접속지 해시가 됐기 때문**이다.
--
--   [무엇이 바뀌었나]
--     013에서 이 칼럼을 넣은 이유는 *"쿠키를 지우고 다시 온 상대"* 를 잡기 위해서였다.
--     그때는 판정 키가 쿠키 번호였고, IP는 **쿠키가 없던 요청에만 보는 보조 수단**이었다.
--
--     이제 비로그인 판정 키가 `i:<접속지 해시>` 로 바뀌었다 →
--     **(post_id, viewer_key) 기본키가 곧 접속지 판정**이라 같은 값을 두 곳에 담게 됐다.
--     ★ 중복은 언젠가 한쪽만 갱신된다. 쓰이지 않는 쪽을 지운다.
--
--   [★ 왜 쿠키를 쓰다가 도로 뺐나 — 되돌린 판단도 이력으로 남긴다]
--     조회 판정 전용 쿠키(`viewer`)를 잠깐 뒀었다. 사람 단위 판정이 훨씬 정확했지만,
--     그건 **기기에 저장하는 행위**라 동의를 받아야 했다. 그래서:
--       · 동의 항목이 하나 늘고
--       · 거절한 사람은 어차피 IP로 판정하게 되어 **길이 둘로 갈라졌다**
--     → **비로그인 조회 판정에는 기기에 아무것도 심지 않는다**로 정리했다.
--
--   [잃은 것도 분명히]
--     · 같은 공유기 뒤 여러 사람이 **한 명**이 된다 (과소 집계)
--     · 모바일은 주소가 자주 바뀌어 같은 사람이 **여러 번** 세어진다 (과대 집계)
--     ※ Discourse도 IP로 판정한다 — 큰 서비스가 그 오차를 감수하고 고른 쪽이다.
-- ============================================================

ALTER TABLE post_views DROP INDEX idx_post_views_ip;
ALTER TABLE post_views DROP COLUMN ip_hash;
